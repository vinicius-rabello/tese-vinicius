"""Shared pieces of the experiment-block generators (make_block_*.py): the
per-architecture batch size and learning rate, and the YAML format train.py
reads. Every block goes through write_config, so blocks can't drift apart."""

import os

import yaml

ARCHS = ("srcnn", "dscms", "prusr", "srno", "sofono")
# Batch size and learning rate per architecture, as used so far (the
# operators' 4e-5 comes from their original papers).
HPARAMS = {
    "srcnn": {"BATCH_SIZE": 32, "LEARNING_RATE": 1e-4},
    "dscms": {"BATCH_SIZE": 32, "LEARNING_RATE": 1e-4},
    "prusr": {"BATCH_SIZE": 32, "LEARNING_RATE": 1e-4},
    # SRNO runs bit-reproducible: cudnn autotuning doesn't speed it up
    # (172.9 vs 172.3 s/epoch) and costs ~1.5 GB of its tight memory.
    "srno": {"BATCH_SIZE": 16, "LEARNING_RATE": 4e-5, "DETERMINISTIC": True},
    "sofono": {"BATCH_SIZE": 8, "LEARNING_RATE": 4e-5},
}
CONFIG_ROOT = os.environ.get(
    "BLOCK_CONFIG_ROOT", os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "configs"))


def lam_tag(lam: float) -> str:
    return f"{lam:g}"


def write_config(block: str, arch: str, lam: float, residual: bool, seed: int, noise: float = 0.0,
                 run_name: str = None, extra: dict = None) -> str:
    """noise > 0 adds NOISE_STD (the noisy regime); the default 0 writes exactly
    the same file as before (no NOISE_STD key, no suffix in the name).
    run_name replaces <block>_<arch> (block E: one name per stage) and extra
    adds keys (STAGE, STAGE1_CHECKPOINT, FIXED_EPOCHS_FROM); both default to
    the previous output."""
    if arch not in HPARAMS:
        raise ValueError(f"Unknown architecture {arch!r}; choose from {ARCHS}.")
    config = {
        "MODEL_NAME": arch,
        # run_id = <RUN_NAME>_<res|nores>_lam<lambda>_seed<seed> (train.py)
        "RUN_NAME": run_name or f"{block}_{arch}",
        "DEVICE": "cuda",
        "NUM_WORKERS": 4,
        **HPARAMS[arch],
        "LAMBDA": float(lam),
        "RESIDUAL": bool(residual),
        "SEED": int(seed),
        "IMAGE_SAVE_INTERVAL": 25,
    }
    if noise > 0:
        config["NOISE_STD"] = float(noise)
    if extra:
        config.update(extra)
    folder = os.path.join(CONFIG_ROOT, block)
    os.makedirs(folder, exist_ok=True)
    noise_tag = f"_noise{noise:g}" if noise > 0 else ""
    path = os.path.join(folder, f"{run_name or block + '_' + arch}_{'res' if residual else 'nores'}_lam{lam_tag(lam)}{noise_tag}_seed{seed}.yaml")
    with open(path, "w") as f:
        f.write(f"# Block {block}: generated by scripts/make_block_{block.lower()}.py -- do not edit by hand.\n")
        yaml.safe_dump(config, f, sort_keys=False)
    return path
