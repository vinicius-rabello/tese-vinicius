#!/bin/bash
# Light backup of the campaign results (results/ stays out of git):
#
#     scripts/backup_results.sh [results dir] [output dir]
#     (defaults: results, /home/lcadame/Vinicius_Thesis/backups)
#
# Writes <output dir>/results_light_<date-time>.zip with, per run, config.json,
# summary.json, train_log.csv, eval_summary*.json and metrics_per_sample*.csv
# (the per-day metrics the bootstrap needs); tables/; the newest test and
# validation reports (report/<stamp>/ and report/<stamp>_val/); DECISIONS.md,
# STATUS.md, OPEN_QUESTIONS.md. No checkpoints (*.pt), no spectra (*.npz: they
# are regenerated by re-evaluating best.pt), no images.
#
# It also writes, next to the zip and inside it, best_pt_<date-time>.txt:
# the best.pt of the main configurations (blocks A, B, C, E: what the main
# tables, the lambda choice and the multistage need) with size and sha256,
# then the others (D, N, ...). Copy those files separately (they are the
# only thing the zip can't rebuild).
set -euo pipefail
cd "$(dirname "$0")/.."

RESULTS=${1:-results}
OUT=${2:-/home/lcadame/Vinicius_Thesis/backups}
STAMP=$(date +%Y%m%d-%H%M)
mkdir -p "$OUT"
ZIP="$(cd "$OUT" && pwd)/results_light_$STAMP.zip"
LIST="$(cd "$OUT" && pwd)/best_pt_$STAMP.txt"

[ -d "$RESULTS" ] || { echo "No results dir: $RESULTS" >&2; exit 1; }

# best.pt list: main configurations first.
{
  echo "# best.pt of the campaign runs, $(date '+%F %T'), results dir: $RESULTS"
  echo "# size_bytes  sha256  path"
  echo "## Main configurations (A, B, C, E)"
  for f in "$RESULTS"/[ABCE]_*/best.pt; do
    if [ -e "$f" ]; then echo "$(stat -c %s "$f")  $(sha256sum "$f" | cut -d' ' -f1)  $f"; fi
  done
  echo "## Other runs (D, N, ...)"
  for f in "$RESULTS"/*/best.pt; do
    case "$(basename "$(dirname "$f")")" in [ABCE]_*) continue ;; esac
    if [ -e "$f" ]; then echo "$(stat -c %s "$f")  $(sha256sum "$f" | cut -d' ' -f1)  $f"; fi
  done
} > "$LIST"

# Files for the zip (paths relative to the repository root).
FILES=$(find "$RESULTS" -mindepth 2 -maxdepth 2 -type f \
  \( -name config.json -o -name summary.json -o -name train_log.csv \
     -o -name 'eval_summary*.json' -o -name 'metrics_per_sample*.csv' \) | sort)
if [ -d tables ]; then FILES="$FILES"$'\n'"$(find tables -type f | sort)"; fi
newest_test=$(ls -1d report/*/ 2>/dev/null | grep -v '_val/$' | sort | tail -1 || true)
newest_val=$(ls -1d report/*_val/ 2>/dev/null | sort | tail -1 || true)
for d in $newest_test $newest_val; do
  FILES="$FILES"$'\n'"$(find "${d%/}" -type f ! -name '*.pt' ! -name '*.png' ! -name '*.zip' | sort)"
done
for f in DECISIONS.md STATUS.md OPEN_QUESTIONS.md; do if [ -e "$f" ]; then FILES="$FILES"$'\n'"$f"; fi; done
FILES=$(printf '%s\n' "$FILES" | grep -v '^$')
if printf '%s\n' "$FILES" | grep -qE '\.(pt|npz)$'; then echo "internal error: a checkpoint or spectrum was selected" >&2; exit 1; fi

printf '%s\n' "$FILES" | zip -q "$ZIP" -@
zip -q -j "$ZIP" "$LIST"          # the best.pt list, at the top of the zip

echo "Zip:  $ZIP ($(du -h "$ZIP" | cut -f1), $(zipinfo -1 "$ZIP" | wc -l) files)"
echo "List: $LIST"
echo "Main-configuration best.pt to copy separately:"
sed -n '/^## Main/,/^## Other/p' "$LIST" | grep -v '^##' | awk '{printf "  %s  (%.1f MB)\n", $3, $1/1e6}'
